CREATE TABLE notificaciones (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  destinatario_id uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  tipo varchar(50) NOT NULL,
  payload jsonb NOT NULL,
  estado varchar(20) NOT NULL DEFAULT 'pendiente',
  intentos integer NOT NULL DEFAULT 0,
  next_attempt_at timestamptz NOT NULL DEFAULT now(),
  last_error text,
  dedupe_key varchar(255) NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  sent_at timestamptz,
  CONSTRAINT notificaciones_estado_valido CHECK (estado IN ('pendiente', 'enviada', 'fallida')),
  CONSTRAINT notificaciones_intentos_no_negativos CHECK (intentos >= 0)
);
CREATE INDEX notificaciones_pendientes_idx ON notificaciones (estado, next_attempt_at);

